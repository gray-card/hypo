#!/usr/bin/env node

import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { format, resolveConfig } from "prettier";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const LEXICON_ROOT = resolve(ROOT, "lexicons");
const REFERENCE_ROOT = resolve(ROOT, "docs/reference/lexicons");
const SIDEBAR_OUTPUT = resolve(ROOT, "docs/site/generated/lexiconSidebar.mjs");
const SUMMARY_OUTPUT = resolve(ROOT, "docs/site/src/data/lexicon-summary.json");
const GENERATED_MARKER = "<!-- Generated by scripts/generate-lexicon-docs.mjs. Do not edit. -->";

const GROUP_LABELS = {
  core: "Core",
  catalog: "Catalog types",
  edit: "Edits",
  gallery: "Gallery",
  instance: "Instances",
  meter: "Metering",
  photo: "Photos",
  process: "Processes",
  rule: "Rules",
  scene: "Scene graphs",
  session: "Sessions",
  workflow: "Workflows",
};

async function jsonFiles(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const nested = await Promise.all(
    entries.map((entry) => {
      const path = resolve(dir, entry.name);
      return entry.isDirectory() ? jsonFiles(path) : entry.name.endsWith(".json") ? [path] : [];
    }),
  );
  return nested.flat().sort();
}

function groupFor(nsid) {
  const parts = nsid.split(".");
  return parts.length === 3 ? "core" : parts[2] || "core";
}

function groupLabel(group) {
  return GROUP_LABELS[group] || group[0].toUpperCase() + group.slice(1);
}

function canonicalRef(ref, currentNsid) {
  if (ref.startsWith("#")) return `${currentNsid}${ref}`;
  return ref.includes("#") ? ref : `${ref}#main`;
}

function splitRef(ref, currentNsid) {
  const canonical = canonicalRef(ref, currentNsid);
  const [nsid, fragment = "main"] = canonical.split("#");
  return { canonical, nsid, fragment };
}

function definitionAnchor(fragment) {
  return String(fragment).toLowerCase();
}

function schemaKind(schema) {
  return schema?.type === "record" ? "object" : schema?.type || "unknown";
}

function makeRegistry(lexicons) {
  return new Map(lexicons.map((lexicon) => [lexicon.id, lexicon]));
}

function groupLexicons(lexicons) {
  const groups = new Map();
  for (const lexicon of lexicons) {
    const group = groupFor(lexicon.id);
    if (!groups.has(group)) groups.set(group, []);
    groups.get(group).push(lexicon);
  }
  return groups;
}

function resolveRef(ref, currentNsid, registry) {
  const target = splitRef(ref, currentNsid);
  const definition = registry.get(target.nsid)?.defs?.[target.fragment];
  if (!definition) {
    throw new Error(`Unresolved lexicon ref ${target.canonical} (from ${currentNsid})`);
  }
  return { ...target, definition, schema: definition.type === "record" ? definition.record : definition };
}

function resolvedSchema(schema, currentNsid, registry, seen = new Set()) {
  if (schema?.type !== "ref") return { schema, currentNsid };
  const target = resolveRef(schema.ref, currentNsid, registry);
  if (seen.has(target.canonical)) return { schema: target.schema, currentNsid: target.nsid };
  const nextSeen = new Set(seen).add(target.canonical);
  return resolvedSchema(target.schema, target.nsid, registry, nextSeen);
}

function inlineCode(value) {
  const text = String(value);
  const fence = text.includes("`") ? "``" : "`";
  return `${fence}${text}${fence}`;
}

export function mdxText(value) {
  // Docusaurus parses Markdown as MDX. Preserve intentional inline-code spans,
  // but escape prose characters that MDX would otherwise treat as JSX or an
  // expression (for instance, "<->" and "{{field.path}}").
  return String(value ?? "")
    .split(/(`+[^`]*`+)/)
    .map((part, index) => {
      if (index % 2 === 1) return part;
      return part
        .replaceAll("&", "&amp;")
        .replaceAll("<", "&lt;")
        .replaceAll(">", "&gt;")
        .replaceAll("{", "&#123;")
        .replaceAll("}", "&#125;");
    })
    .join("");
}

function cell(value) {
  return String(value ?? "")
    .replaceAll("|", "\\|")
    .replaceAll("\n", " ")
    .trim();
}

function refLink(ref, currentNsid, pageNsid = currentNsid) {
  const { canonical, nsid, fragment } = splitRef(ref, currentNsid);
  const anchor = definitionAnchor(fragment);
  const href = nsid === pageNsid ? `#${anchor}` : `./${nsid}.md#${anchor}`;
  return `[${inlineCode(canonical)}](${href})`;
}

function knownValuesFor(schema, currentNsid, registry, seen = new Set()) {
  if (Array.isArray(schema?.knownValues)) return schema.knownValues;
  if (schema?.type === "array") return knownValuesFor(schema.items, currentNsid, registry, seen);
  if (schema?.type === "ref") {
    const target = resolveRef(schema.ref, currentNsid, registry);
    if (seen.has(target.canonical)) return [];
    return knownValuesFor(target.schema, target.nsid, registry, new Set(seen).add(target.canonical));
  }
  if (schema?.type === "union") {
    return [
      ...new Set(
        (schema.refs || []).flatMap((ref) => {
          const target = resolveRef(ref, currentNsid, registry);
          if (seen.has(target.canonical)) return [];
          return knownValuesFor(target.schema, target.nsid, registry, new Set(seen).add(target.canonical));
        }),
      ),
    ];
  }
  return [];
}

function typeLabel(schema, currentNsid, registry, pageNsid = currentNsid) {
  if (!schema || typeof schema !== "object") return inlineCode("unknown");
  if (schema.type === "record") return inlineCode("record");
  if (schema.type === "ref") {
    const target = resolveRef(schema.ref, currentNsid, registry);
    const resolved = resolvedSchema(target.schema, target.nsid, registry);
    return `${refLink(schema.ref, currentNsid, pageNsid)} → ${inlineCode(schemaKind(resolved.schema))}`;
  }
  if (schema.type === "union") {
    const refs = (schema.refs || []).map((ref) => {
      const target = resolveRef(ref, currentNsid, registry);
      return `${refLink(ref, currentNsid, pageNsid)} (${schemaKind(target.schema)})`;
    });
    return refs.length ? refs.join("<br />") : inlineCode("union");
  }
  if (schema.type === "array")
    return `${inlineCode("array")} of ${typeLabel(schema.items, currentNsid, registry, pageNsid)}`;
  if (schema.type === "string" && schema.format) return `${inlineCode("string")} (${inlineCode(schema.format)})`;
  return inlineCode(schema.type || "unknown");
}

function constraintLabel(schema) {
  if (!schema || typeof schema !== "object") return "";
  const keys = ["minLength", "maxLength", "minGraphemes", "maxGraphemes", "minimum", "maximum", "maxSize"];
  const parts = keys.filter((key) => schema[key] !== undefined).map((key) => `${key}=${schema[key]}`);
  if (Array.isArray(schema.accept)) parts.push(`accept=${schema.accept.join(", ")}`);
  return parts.map(inlineCode).join("<br />");
}

function descriptionFor(schema, currentNsid, registry) {
  if (schema?.description) return mdxText(schema.description);
  if (schema?.type !== "ref") return "";
  return mdxText(resolveRef(schema.ref, currentNsid, registry).definition.description || "");
}

function fieldRows(schema, currentNsid, registry, prefix = "", stack = new Set(), depth = 0, pageNsid = currentNsid) {
  const resolved = resolvedSchema(schema, currentNsid, registry);
  if (resolved.schema?.type !== "object") return [];

  const required = new Set(resolved.schema.required || []);
  const rows = [];
  for (const [name, property] of Object.entries(resolved.schema.properties || {})) {
    const path = `${prefix}${name}`;
    const knownValues = knownValuesFor(property, resolved.currentNsid, registry);
    rows.push({
      path,
      required: required.has(name),
      type: typeLabel(property, resolved.currentNsid, registry, pageNsid),
      constraints: constraintLabel(property),
      knownValues: knownValues.map(inlineCode).join("<br />"),
      description: descriptionFor(property, resolved.currentNsid, registry),
    });

    // One level of expansion makes a referenced object's fields visible without
    // repeating the complete shared-def tree on every page.
    if (depth >= 1) continue;
    let targetSchema = property;
    let targetNsid = resolved.currentNsid;
    let key = `${resolved.currentNsid}#inline:${path}`;
    if (property.type === "array") targetSchema = property.items;
    if (targetSchema?.type === "ref") {
      const target = resolveRef(targetSchema.ref, targetNsid, registry);
      targetSchema = target.schema;
      targetNsid = target.nsid;
      key = target.canonical;
    }
    const object = resolvedSchema(targetSchema, targetNsid, registry);
    if (object.schema?.type !== "object" || stack.has(key)) continue;
    const childPrefix = property.type === "array" ? `${path}[].` : `${path}.`;
    rows.push(
      ...fieldRows(targetSchema, targetNsid, registry, childPrefix, new Set(stack).add(key), depth + 1, pageNsid),
    );
  }
  return rows;
}

function refsIn(value, currentNsid, out = new Set()) {
  if (Array.isArray(value)) {
    value.forEach((item) => refsIn(item, currentNsid, out));
    return out;
  }
  if (!value || typeof value !== "object") return out;
  if (typeof value.ref === "string") out.add(canonicalRef(value.ref, currentNsid));
  if (Array.isArray(value.refs)) value.refs.forEach((ref) => out.add(canonicalRef(ref, currentNsid)));
  Object.values(value).forEach((child) => refsIn(child, currentNsid, out));
  return out;
}

function renderTable(headers, rows) {
  if (!rows.length) return "_None._\n";
  return [
    `| ${headers.join(" | ")} |`,
    `| ${headers.map(() => "---").join(" | ")} |`,
    ...rows.map((row) => `| ${row.map(cell).join(" | ")} |`),
    "",
  ].join("\n");
}

function renderDefinition(defName, definition, lexicon, registry) {
  const sourceSchema = definition.type === "record" ? definition.record : definition;
  const lines = [`<a id="${definitionAnchor(defName)}"></a>`, "", `## ${inlineCode(defName)}`, ""];
  if (definition.description) lines.push(mdxText(definition.description), "");
  lines.push(`**Kind:** ${inlineCode(definition.type || "unknown")}`);
  if (definition.type === "record") lines.push(`**Record key:** ${inlineCode(definition.key || "any")}`);
  lines.push("");

  const fields = fieldRows(sourceSchema, lexicon.id, registry, "", new Set(), 0, lexicon.id);
  if (fields.length) {
    lines.push(
      "### Resolved fields",
      "",
      "Referenced object fields are expanded once. A linked type name opens the definition that supplies the field.",
      "",
      renderTable(
        ["Field", "Required", "Type / resolved ref", "Constraints", "Known values", "Description"],
        fields.map((field) => [
          inlineCode(field.path),
          field.required ? "yes" : "no",
          field.type,
          field.constraints,
          field.knownValues,
          field.description,
        ]),
      ),
    );
  } else {
    const values = knownValuesFor(sourceSchema, lexicon.id, registry);
    lines.push(`**Resolved type:** ${typeLabel(sourceSchema, lexicon.id, registry, lexicon.id)}`, "");
    if (values.length) lines.push(`**Known values:** ${values.map(inlineCode).join(", ")}`, "");
    const constraints = constraintLabel(sourceSchema);
    if (constraints) lines.push(`**Constraints:** ${constraints}`, "");
  }
  return lines.join("\n");
}

function renderLexicon(lexicon, sourceFile, registry) {
  const definitions = Object.entries(lexicon.defs || {});
  const primary = lexicon.defs?.main;
  const summary = primary?.description || definitions.find(([, definition]) => definition.description)?.[1].description;
  const refs = [...refsIn(lexicon, lexicon.id)].sort();
  const sourcePath = relative(ROOT, sourceFile);
  const lines = [
    "---",
    `title: "${lexicon.id}"`,
    `sidebar_label: "${lexicon.id.split(".").at(-1)}"`,
    `description: "Generated reference for ${lexicon.id}."`,
    "hide_title: true",
    "---",
    "",
    GENERATED_MARKER,
    "",
    `# ${inlineCode(lexicon.id)}`,
    "",
    mdxText(summary || "This page documents the definitions declared by this NSID."),
    "",
    `- **Source:** ${inlineCode(sourcePath)}`,
    `- **Lexicon version:** ${inlineCode(lexicon.lexicon)}`,
    `- **Definitions:** ${definitions.length}`,
    "",
  ];

  if (refs.length) {
    lines.push(
      "## Resolved references",
      "",
      renderTable(
        ["Reference", "Resolved kind"],
        refs.map((ref) => {
          const target = resolveRef(ref, lexicon.id, registry);
          return [refLink(ref, lexicon.id, lexicon.id), inlineCode(schemaKind(target.schema))];
        }),
      ),
    );
  }

  definitions.forEach(([defName, definition]) => {
    lines.push(renderDefinition(defName, definition, lexicon, registry), "");
  });
  return `${lines.join("\n").trimEnd()}\n`;
}

function renderIndex(lexicons) {
  const groups = groupLexicons(lexicons);
  const recordCount = lexicons.filter((lexicon) => lexicon.defs?.main?.type === "record").length;
  const lines = [
    "---",
    "title: Lexicon NSIDs",
    "sidebar_label: Overview",
    "description: Generated index of app.graycard lexicon namespaces.",
    "hide_title: true",
    "---",
    "",
    GENERATED_MARKER,
    "",
    "# Lexicon NSIDs",
    "",
    `This index covers ${lexicons.length} NSIDs: ${recordCount} record collections and ${lexicons.length - recordCount} definition-only namespaces. Each page resolves refs, field shapes, constraints, and known values from the source JSON.`,
    "",
    "> `knownValues` are open suggestions in the AT Protocol lexicon model. Clients should preserve unfamiliar string values.",
    "",
  ];
  for (const [group, members] of [...groups].sort(([a], [b]) => groupLabel(a).localeCompare(groupLabel(b)))) {
    lines.push(`## ${groupLabel(group)}`, "");
    lines.push(
      renderTable(
        ["NSID", "Kind", "Definitions", "Summary"],
        members.map((lexicon) => {
          const main = lexicon.defs?.main;
          const summary =
            main?.description || Object.values(lexicon.defs || {}).find((def) => def.description)?.description || "";
          return [
            `[${inlineCode(lexicon.id)}](./${lexicon.id}.md)`,
            inlineCode(main?.type === "record" ? "record" : "definitions"),
            Object.keys(lexicon.defs || {}).length,
            mdxText(summary),
          ];
        }),
      ),
    );
  }
  return `${lines.join("\n").trimEnd()}\n`;
}

function renderSidebar(lexicons) {
  const groups = groupLexicons(lexicons);
  const items = [...groups]
    .sort(([a], [b]) => groupLabel(a).localeCompare(groupLabel(b)))
    .map(([group, members]) => ({
      type: "category",
      label: groupLabel(group),
      collapsed: true,
      items: members.map((lexicon) => `reference/lexicons/${lexicon.id}`),
    }));
  return `// Generated by scripts/generate-lexicon-docs.mjs. Do not edit.\n\nexport const lexiconSidebarItems = ${JSON.stringify(items, null, 2)};\n`;
}

async function writeGenerated(path, contents) {
  const config = (await resolveConfig(path)) || {};
  await writeFile(path, await format(contents, { ...config, filepath: path }));
}

async function removeStalePages(expected) {
  let entries = [];
  try {
    entries = await readdir(REFERENCE_ROOT, { withFileTypes: true });
  } catch (error) {
    if (error.code === "ENOENT") return;
    throw error;
  }
  for (const entry of entries) {
    if (!entry.isFile() || !entry.name.endsWith(".md") || expected.has(entry.name)) continue;
    const path = resolve(REFERENCE_ROOT, entry.name);
    const contents = await readFile(path, "utf8");
    if (contents.includes(GENERATED_MARKER)) await rm(path);
  }
}

export async function generateLexiconDocs() {
  const files = await jsonFiles(LEXICON_ROOT);
  const sources = await Promise.all(
    files.map(async (file) => ({ file, lexicon: JSON.parse(await readFile(file, "utf8")) })),
  );
  sources.sort((a, b) => a.lexicon.id.localeCompare(b.lexicon.id));

  const ids = sources.map(({ lexicon }) => lexicon.id);
  if (new Set(ids).size !== ids.length) throw new Error("Lexicon NSIDs must be unique");
  const registry = makeRegistry(sources.map(({ lexicon }) => lexicon));
  // Resolve every declared ref before writing anything, so a broken source cannot
  // leave a partially regenerated reference tree.
  for (const { lexicon } of sources) {
    for (const ref of refsIn(lexicon, lexicon.id)) resolveRef(ref, lexicon.id, registry);
  }

  await mkdir(REFERENCE_ROOT, { recursive: true });
  await mkdir(dirname(SIDEBAR_OUTPUT), { recursive: true });
  await mkdir(dirname(SUMMARY_OUTPUT), { recursive: true });
  const expected = new Set(["index.md", ...ids.map((id) => `${id}.md`)]);
  await removeStalePages(expected);
  await Promise.all(
    sources.map(({ file, lexicon }) =>
      writeGenerated(resolve(REFERENCE_ROOT, `${lexicon.id}.md`), renderLexicon(lexicon, file, registry)),
    ),
  );
  await writeGenerated(resolve(REFERENCE_ROOT, "index.md"), renderIndex(sources.map(({ lexicon }) => lexicon)));
  await writeGenerated(SIDEBAR_OUTPUT, renderSidebar(sources.map(({ lexicon }) => lexicon)));

  const recordCount = sources.filter(({ lexicon }) => lexicon.defs?.main?.type === "record").length;
  const definitionCount = sources.reduce((count, { lexicon }) => count + Object.keys(lexicon.defs || {}).length, 0);
  await writeGenerated(
    SUMMARY_OUTPUT,
    `${JSON.stringify({ nsids: sources.length, records: recordCount, definitions: definitionCount }, null, 2)}\n`,
  );
  return { nsids: sources.length, records: recordCount, definitions: definitionCount };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const result = await generateLexiconDocs();
  console.log(
    `Generated docs/reference/lexicons, ${relative(ROOT, SIDEBAR_OUTPUT)}, and ${relative(ROOT, SUMMARY_OUTPUT)} from ${result.nsids} lexicons (${result.records} records).`,
  );
}
