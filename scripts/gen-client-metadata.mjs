#!/usr/bin/env node
// gen-client-metadata.mjs: keep the web and native client metadata plus the
// native Swift constants aligned with src/oauthScope.js.
//
//   node scripts/gen-client-metadata.mjs [--check]

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { OAUTH_SCOPE } from "../src/oauthScope.js";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const CHECK = process.argv.includes("--check");
const IOS_CLIENT_ID = "https://hypo.graycard.app/ios-client-metadata.json";
const IOS_REDIRECT_URI = "app.graycard.hypo:/oauth/callback";

const outputs = [];

for (const name of ["client-metadata.json", "ios-client-metadata.json"]) {
  const path = join(ROOT, "public", name);
  const metadata = JSON.parse(readFileSync(path, "utf8"));
  metadata.scope = OAUTH_SCOPE;
  outputs.push([path, JSON.stringify(metadata, null, 2) + "\n"]);
}

const swiftScopeLines = OAUTH_SCOPE.split(" ")
  .map((scope) => `        "${scope}",`)
  .join("\n");
const swift = `// Generated by scripts/gen-client-metadata.mjs. Do not edit.
import Foundation

enum HypoOAuthConfiguration {
    static let clientID = "${IOS_CLIENT_ID}"
    static let redirectURI = URL(string: "${IOS_REDIRECT_URI}")!
    static let scope = [
${swiftScopeLines}
    ].joined(separator: " ")
}
`;
outputs.push([join(ROOT, "apps", "ios", "App", "HypoOAuthConfiguration.generated.swift"), swift]);

let drifted = false;
for (const [path, contents] of outputs) {
  if (CHECK) {
    if (readFileSync(path, "utf8") !== contents) {
      console.error(`${path} is out of date; run node scripts/gen-client-metadata.mjs`);
      drifted = true;
    }
  } else {
    writeFileSync(path, contents);
  }
}

if (drifted) process.exit(1);
console.log(`${CHECK ? "checked" : "updated"} OAuth client artifacts (${OAUTH_SCOPE.split(" ").length} scopes)`);
